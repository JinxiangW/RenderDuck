"""Run under the application's embedded Python, then compare with check.py."""
import hashlib
import json
import os
import sys

runtime, capture, output = sys.argv[1:]
sys.path.insert(0, os.path.join(runtime, 'pymodules'))
import riderduck as rd
rd.InitialiseReplay(rd.GlobalEnvironment(), [])
cap = rd.OpenCaptureFile()
assert cap.OpenFile(capture, '', None) == rd.ResultCode.Succeeded
status, r = cap.OpenCapture(rd.ReplayOptions(), None)
assert status == rd.ResultCode.Succeeded, str(status)
try:
    def walk(actions):
        for a in actions:
            yield a
            yield from walk(a.children)
    actions = list(walk(r.GetRootActions()))
    resources = {x.name: rd.ResourceId(x.resourceId) for x in r.GetResources()}
    names = [(str(x.resourceId), x.name, x.autogeneratedName) for x in r.GetResources()
             if x.type == rd.ResourceType.Buffer]
    assert any(n == 'SharedBuffer' for _, n, _ in names), names
    assert any(n == '\u76f8\u673aBuffer' for _, n, _ in names), names
    assert any(n == 'RawName' for _, n, _ in names), names
    assert not any(n in ('OldSharedName', 'MustBeCleared') for _, n, _ in names), names
    assert any(auto for _, _, auto in names), names
    shaders = {}
    for a in actions:
        if not a.flags & rd.ActionFlags.Drawcall:
            continue
        r.SetFrameEvent(a.eventId, True)
        p = r.GetPipelineState()
        for stage, label in [(rd.ShaderStage.Vertex, 'VS'), (rd.ShaderStage.Pixel, 'PS')]:
            ref = p.GetShaderReflection(stage)
            block_index = next(i for i, block in enumerate(ref.constantBlocks) if block.fixedBindNumber == 0)
            assert p.GetConstantBlock(stage, block_index, 0).descriptor.resource == resources['SharedBuffer']
            shader = str(p.GetShader(stage))
            if shader in shaders: continue
            shaders[shader] = dict(stage=label, md5=hashlib.md5(bytes(ref.rawBytes)).hexdigest(),
                                   blocks=[dict(name=b.name, slot=b.fixedBindNumber,
                                     variables=[dict(name=v.name, offset=v.byteOffset,
                                                     rows=v.type.rows, columns=v.type.columns)
                                                for v in b.variables]) for b in ref.constantBlocks])
    blocks = [b for shader in shaders.values() for b in shader['blocks']]
    camera = next(b for b in blocks if b['name'] == 'CameraConstants')
    assert camera['variables'][0] == dict(name='ViewProjection', offset=0, rows=4, columns=4), camera
    assert camera['variables'][1]['name'] == 'CameraPosition'
    assert any(b['name'] == 'MaterialConstants' for b in blocks)
    assert any(b['name'] == 'PassConstants' for b in blocks)
    assert any(b['name'] == 'cbuffer0' for b in blocks)
    r.SetFrameEvent(actions[-1].eventId, True)
    images = {}
    for i in range(4):
        data = bytes(r.GetTextureData(resources['Output{}'.format(i)], rd.Subresource()))
        assert len(data) == 64 * 64 * 4
        assert bytes([255, 0, 0, 255]) in data, 'fixture only cleared; it did not rasterise'
        images[str(i)] = hashlib.sha256(data).hexdigest()
    assert len(set(images.values())) == 1, images
    with open(output, 'w', encoding='utf-8') as f:
        json.dump(dict(buffer_names=names, shaders=shaders, image_hashes=images), f, indent=2)
    print('PASS: resource names, reflection names/layout, shared-buffer declarations, rendered outputs')
finally:
    r.Shutdown()
    cap.Shutdown()
    rd.ShutdownReplay()
